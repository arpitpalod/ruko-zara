const DICTS: Record<Lang, Dict> = { en, hi, hinglish };
const STORAGE_KEY = 'ruko-zara.lang';

export type T = (key: Key, vars?: Record<string, string | number>) => string;

function translate(lang: Lang): T {
  const d = DICTS[lang];
  return (key, vars) => {
    // "1 opinion" vs "2 opinions": a key ending in _one is used when n is 1.
    const one = vars?.n === 1 ? (`${key}_one` as Key) : null;
    const s = (one && (d[one] ?? en[one as keyof typeof en])) || d[key] || en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
  };
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T } | null>(null);

export function useT() {
  const c = useContext(Ctx);
  if (!c) throw new Error('useT outside LanguageProvider');
  return c;
}

/** Loads the saved language; on first launch asks the user to pick one. */
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang | null>(null);
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((v) => {
        if (v === 'en' || v === 'hi' || v === 'hinglish') return setLangState(v);
        // A shared arzi opens straight away, in the sharer's language; the header button changes it.
        if (Platform.OS !== 'web' || typeof window === 'undefined') return;
        const l = langFromLink(window.location.pathname, window.location.search, navigator.language);
        if (l) {
          setLangState(l);
          AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
        }
      })
      .catch(() => {})
      .finally(() => setLoaded(true));
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  if (!loaded) return null;
  if (!lang) return <LanguagePicker onPick={setLang} />;

  return <Ctx.Provider value={{ lang, setLang, t: translate(lang) }}>{children}</Ctx.Provider>;
}

